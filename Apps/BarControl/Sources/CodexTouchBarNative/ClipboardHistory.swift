import AppKit

@MainActor
final class ClipboardHistoryStore {
    static let shared = ClipboardHistoryStore()

    struct Entry: Identifiable {
        enum Content: Equatable {
            case text(String, rtf: Data?, html: Data?)
            case image(Data, NSPasteboard.PasteboardType)
        }

        let id = UUID()
        let content: Content
        let sourceIcon: NSImage?

        var isImage: Bool {
            if case .image = content { return true }
            return false
        }

        var displayText: String {
            switch content {
            case .text(let text, _, _):
                return text.replacingOccurrences(of: "\n", with: " ")
                    .replacingOccurrences(of: "\r", with: " ")
                    .trimmingCharacters(in: .whitespacesAndNewlines)
            case .image:
                return "图片"
            }
        }

        var thumbnail: NSImage? {
            guard case .image(let data, _) = content else { return nil }
            return NSImage(data: data)
        }
    }

    private let pasteboard = NSPasteboard.general
    private let limit = 12
    private let maximumImageBytes = 8 * 1_024 * 1_024
    private let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private let generated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private(set) var entries: [Entry] = []
    var onChange: (() -> Void)?
    private var timer: Timer?
    private var lastChangeCount = -1
    private(set) var isPaused = false

    func start() {
        guard timer == nil else { return }
        captureCurrent()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.captureCurrent() }
        }
        self.timer = timer
        RunLoop.main.add(timer, forMode: .common)
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func togglePaused() {
        isPaused.toggle()
        onChange?()
    }

    func clear() {
        entries.removeAll()
        onChange?()
    }

    @discardableResult
    func copy(_ entry: Entry) -> Bool {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        switch entry.content {
        case .text(let text, let rtf, let html):
            item.setString(text, forType: .string)
            if let rtf { item.setData(rtf, forType: .rtf) }
            if let html { item.setData(html, forType: .html) }
        case .image(let data, let type):
            item.setData(data, forType: type)
        }
        guard pasteboard.writeObjects([item]) else { return false }
        lastChangeCount = pasteboard.changeCount
        return true
    }

    private func captureCurrent() {
        guard !isPaused else { return }
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        let types = Set(pasteboard.types ?? [])
        guard !types.contains(concealed), !types.contains(transient), !types.contains(generated) else { return }

        let content: Entry.Content
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
           text.count <= 8_000 {
            content = .text(text, rtf: pasteboard.data(forType: .rtf), html: pasteboard.data(forType: .html))
        } else if let image = captureImage(types: types) {
            content = image
        } else {
            return
        }

        let frontmost = NSWorkspace.shared.frontmostApplication
        let sourceIcon = frontmost?.bundleIdentifier == Bundle.main.bundleIdentifier ? nil : frontmost?.icon
        let entry = Entry(content: content, sourceIcon: sourceIcon)
        entries.removeAll { $0.content == content }
        entries.insert(entry, at: 0)
        if entries.count > limit { entries.removeLast(entries.count - limit) }
        onChange?()
    }

    private func captureImage(types: Set<NSPasteboard.PasteboardType>) -> Entry.Content? {
        for type in [NSPasteboard.PasteboardType.png, .tiff] where types.contains(type) {
            guard let data = pasteboard.data(forType: type), data.count <= maximumImageBytes else { continue }
            return .image(data, type)
        }
        return nil
    }
}

@MainActor
final class ClipboardHistoryStripView: NSView {
    var onCopy: ((ClipboardHistoryStore.Entry) -> Void)?
    var onInteraction: (() -> Void)?
    private var entries: [ClipboardHistoryStore.Entry] = []
    private let scrollView = NSScrollView()
    private let itemGap: CGFloat = 4
    private let horizontalInset: CGFloat = 4
    private let minimumItemWidth: CGFloat = 72
    private let maximumItemWidth: CGFloat = 187

    init(width: CGFloat) {
        super.init(frame: NSRect(x: 0, y: 0, width: width, height: 30))
        scrollView.frame = bounds
        scrollView.hasHorizontalScroller = false
        scrollView.hasVerticalScroller = false
        scrollView.drawsBackground = false
        scrollView.borderType = .noBorder
        scrollView.horizontalScrollElasticity = .allowed
        scrollView.verticalScrollElasticity = .none
        addSubview(scrollView)
        scrollView.contentView.postsBoundsChangedNotifications = true
        NotificationCenter.default.addObserver(
            self,
            selector: #selector(didScroll),
            name: NSView.boundsDidChangeNotification,
            object: scrollView.contentView
        )
    }

    @objc private func didScroll(_ note: Notification) {
        onInteraction?()
    }

    deinit {
        NotificationCenter.default.removeObserver(self)
    }

    required init?(coder: NSCoder) {
        fatalError("init(coder:) has not been implemented")
    }

    func update(entries: [ClipboardHistoryStore.Entry]) {
        self.entries = entries
        let itemWidths = entries.map(itemWidth(for:))
        let gapsWidth = CGFloat(max(0, entries.count - 1)) * itemGap
        let contentWidth = max(
            bounds.width,
            horizontalInset * 2
                + itemWidths.reduce(0, +)
                + gapsWidth
        )
        let row = NSView(frame: NSRect(x: 0, y: 0, width: contentWidth, height: bounds.height))
        var x = horizontalInset

        for (entry, width) in zip(entries, itemWidths) {
            let button = ClipboardPillButton(frame: NSRect(x: x, y: 2, width: width, height: 26))
            button.title = entry.displayText
            button.thumbnail = entry.thumbnail
            button.sourceIcon = entry.isImage ? nil : entry.sourceIcon
            button.textFontSize = Self.textFont.pointSize
            button.maximumTextWidth = Self.maximumTextWidth
            button.textInsets = Self.textInsets
            button.lines = Self.wrappedLines(
                entry.displayText,
                maxWidth: Self.maximumTextWidth,
                font: Self.textFont
            )
            button.contentTintColor = .white
            button.isBordered = false
            button.toolTip = entry.displayText
            button.identifier = NSUserInterfaceItemIdentifier(entry.id.uuidString)
            button.target = self
            button.action = #selector(copyEntry(_:))
            row.addSubview(button)
            x += width + itemGap
        }

        scrollView.documentView = row
        scrollView.contentView.scroll(to: .zero)
        scrollView.reflectScrolledClipView(scrollView.contentView)
    }

    private func itemWidth(for entry: ClipboardHistoryStore.Entry) -> CGFloat {
        let lines = Self.wrappedLines(
            entry.displayText,
            maxWidth: Self.maximumTextWidth,
            font: Self.textFont
        )
        let textWidth = lines.map {
            ceil(($0 as NSString).size(withAttributes: [.font: Self.textFont]).width)
        }.max() ?? 0
        let textInsetWidth = Self.textInsets.left + Self.textInsets.right
        if entry.isImage {
            return max(minimumItemWidth, 34 + 6 + textWidth + textInsetWidth + 2)
        }
        if entry.sourceIcon != nil {
            return min(maximumItemWidth, max(minimumItemWidth, 17 + 6 + textWidth + textInsetWidth + 2))
        }
        return min(maximumItemWidth, max(minimumItemWidth, textWidth + textInsetWidth + 2))
    }

    @objc private func copyEntry(_ sender: NSButton) {
        onInteraction?()
        guard let id = sender.identifier?.rawValue,
              let uuid = UUID(uuidString: id),
              let entry = entries.first(where: { $0.id == uuid }) else { return }
        onCopy?(entry)
    }

    private static let textFont = NSFont.systemFont(ofSize: 8, weight: .medium)
    private static let maximumTextWidth: CGFloat = 147
    private static let textInsets = NSEdgeInsets(top: 3, left: 7, bottom: 3, right: 7)

    private static func wrappedLines(_ text: String, maxWidth: CGFloat, font: NSFont) -> [String] {
        let characters = Array(text)
        var start = 0
        var lines: [String] = []
        for _ in 0..<2 {
            var end = start
            while end < characters.count {
                let candidate = String(characters[start...end])
                if (candidate as NSString).size(withAttributes: [.font: font]).width > maxWidth { break }
                end += 1
            }
            if end == start, start < characters.count { end += 1 }
            lines.append(String(characters[start..<min(end, characters.count)]))
            start = end
        }
        if start < characters.count, lines.count == 2 {
            while !lines[1].isEmpty,
                  (lines[1] + "…" as NSString).size(withAttributes: [.font: font]).width > maxWidth {
                lines[1].removeLast()
            }
            lines[1] += "…"
        }
        return lines
    }
}

@MainActor
private final class ClipboardPillButton: NSButton {
    var lines: [String] = [] { didSet { needsDisplay = true } }
    var textFontSize: CGFloat = 8 { didSet { needsDisplay = true } }
    var maximumTextWidth: CGFloat = 147 { didSet { needsDisplay = true } }
    var textInsets = NSEdgeInsets(top: 3, left: 7, bottom: 3, right: 7) { didSet { needsDisplay = true } }
    private let lineHeight: CGFloat = 11

    var thumbnail: NSImage? { didSet { needsDisplay = true } }
    var sourceIcon: NSImage? { didSet { needsDisplay = true } }

    override func draw(_ dirtyRect: NSRect) {
        let background = (cell?.isHighlighted == true)
            ? NSColor(white: 0.30, alpha: 1)
            : NSColor(white: 0.19, alpha: 1)
        background.setFill()
        NSBezierPath(roundedRect: bounds.insetBy(dx: 0.5, dy: 0.5), xRadius: 8, yRadius: 8).fill()

        let contentX = bounds.minX + textInsets.left
        let textStartX: CGFloat
        if let thumbnail {
            let imageRect = NSRect(x: contentX, y: bounds.midY - 12, width: 34, height: 24)
            NSGraphicsContext.saveGraphicsState()
            NSBezierPath(roundedRect: imageRect, xRadius: 6, yRadius: 6).addClip()
            thumbnail.draw(in: imageRect, from: .zero, operation: .sourceOver, fraction: 1)
            NSGraphicsContext.restoreGraphicsState()
            textStartX = imageRect.maxX + 6
        } else if let sourceIcon {
            let imageRect = NSRect(x: contentX, y: bounds.midY - 8.5, width: 17, height: 17)
            sourceIcon.draw(in: imageRect, from: .zero, operation: .sourceOver, fraction: 1)
            textStartX = imageRect.maxX + 6
        } else {
            textStartX = contentX
        }

        guard !title.isEmpty else { return }
        let textWidth = max(1, bounds.maxX - textStartX - textInsets.right)
        let width = min(maximumTextWidth, textWidth)
        let font = NSFont.systemFont(ofSize: textFontSize, weight: .medium)
        let displayLines = lines.isEmpty ? [title] : lines
        for (index, line) in displayLines.prefix(2).enumerated() {
            let rect = NSRect(
                x: textStartX,
                y: bounds.maxY - textInsets.top - lineHeight * CGFloat(index + 1),
                width: width,
                height: lineHeight
            )
            draw(line, in: rect, font: font)
        }
    }

    private func draw(_ line: String, in rect: NSRect, font: NSFont) {
        let paragraph = NSMutableParagraphStyle()
        paragraph.alignment = .left
        paragraph.lineBreakMode = .byTruncatingTail
        (line as NSString).draw(
            in: rect,
            withAttributes: [
                .font: font,
                .foregroundColor: NSColor.white,
                .paragraphStyle: paragraph
            ]
        )
    }
}
